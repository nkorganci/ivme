CREATE TABLE math_tutoring_lessons (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    lesson_date date NOT NULL,
    start_time time NOT NULL,
    end_time time NOT NULL,
    topic varchar(1000) NOT NULL DEFAULT '',
    homework varchar(2000) NOT NULL DEFAULT '',
    status varchar(16) NOT NULL DEFAULT 'PLANNED',
    CONSTRAINT ck_math_tutoring_times CHECK (end_time > start_time),
    CONSTRAINT ck_math_tutoring_status CHECK (status IN ('PLANNED', 'COMPLETED', 'CANCELLED'))
);
CREATE INDEX ix_math_tutoring_user_date ON math_tutoring_lessons(user_id, lesson_date, start_time, id);

CREATE TABLE math_tutoring_files (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id bigint NOT NULL REFERENCES math_tutoring_lessons(id) ON DELETE CASCADE,
    original_name varchar(255) NOT NULL,
    content_type varchar(255) NOT NULL,
    content bytea NOT NULL
);
CREATE INDEX ix_math_tutoring_files_lesson ON math_tutoring_files(lesson_id, id);
