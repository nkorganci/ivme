// Prefer a specific child title over a general unit heading. Only the current
// exam's canonical topics are eligible, preventing TYT/AYT alias duplication.
export function matchTopics(text, branch, allowedTopics) {
  const normalized = normalise(text);
  const matches = (rules[branch] || []).filter(r => !allowedTopics || allowedTopics.has(r.topic))
    .map(r => ({ ...r, length: normalized.match(r.pattern)?.[0].length || 0 })).filter(r => r.length)
    .sort((a, b) => b.length - a.length);
  return matches.length ? [matches[0].topic] : [];
}

export function cleanHeading(value) {
  return String(value).replace(/^[\s,/-]+|[\s,/-]+$/g, '')
    .replace(/(?:\s+|\s*[-–—]\s*)(?:I{1,3}|IV|VI{0,3}|IX|X|\d{1,2})\s*$/u, '')
    .replace(/\s*\(B[oö]l[uü]m\s*\d+\)\s*$/iu, '')
    .replace(/\s*[-–—]?\s*(?:KONU DEĞERLENDİRME|ÜNİTE DEĞERLENDİRME|SORU ÇÖZÜM(?:Ü|LERİ)|ETKİNLİK)\s*$/iu, '')
    .replace(/\s+/g, ' ').trim();
}

