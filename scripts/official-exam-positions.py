"""Generate the immutable booklet-position migration from preserved official identities.

No network or database writes. Composite cards require individual questions and
are deliberately left out of the playable archive. Alternate religion-exempt
questions are not part of the standard 120/80 question profiles.
"""
import hashlib
import json
from pathlib import Path
import re

APP = Path(__file__).resolve().parents[1]
SOURCE = APP.parent / 'veri-hatti/ogm-yks-cikmis/ham/sorular_son.json'
OUTPUT = APP / 'backend/src/main/resources/db/migration/V57__official_exam_positions.sql'
REGISTRY_OUTPUT = APP / 'backend/src/main/resources/db/migration/V58__durable_official_exam_registry.sql'


def generate():
    raw = SOURCE.read_bytes()
    positions = []
    seen = set()
    for row in json.loads(raw)['sorular']:
        if len(row.get('cevaplar') or []) != 1 or row.get('din_yerine'):
            continue
        identities = {row.get('eski_id') or ''} | {
            value.split('#')[0] for value in row.get('eski_yuvalar', [])}
        parsed = set()
        for identity in identities:
            match = re.fullmatch(r'(\d{4})-(TYT|AYT)-([A-Z0-9]+)-(\d+)', identity)
            if match:
                parsed.add((int(match[1]), match[2], match[3], int(match[4])))
        if len(parsed) != 1:
            continue
        year, exam, test, number = parsed.pop()
        order = {'TYT': ['TUR', 'SOS', 'TEM', 'FEN'], 'AYT': ['TDE', 'SB2', 'MAT', 'FEN']}[exam]
        if test not in order:
            continue
        identity = (year, exam, test, number)
        if identity in seen:
            raise ValueError(f'Duplicate official question: {identity}')
        seen.add(identity)
        values = [row['id'], year, exam, row['exam_ders'], order.index(test) * 100 + number]
        positions.append('(' + ','.join(str(v) if isinstance(v, int) else "'" + v.replace("'", "''") + "'" for v in values) + ')')
    sql = f"""-- Generated by scripts/official-exam-positions.py; preserved source SHA256 {hashlib.sha256(raw).hexdigest()}.
-- Identity/order only: does not change question content, labels, answers or learner history.
CREATE TABLE exam_archive_positions (
    question_id bigint PRIMARY KEY REFERENCES questions(id) ON DELETE CASCADE,
    exam_year integer NOT NULL,
    exam_type varchar(3) NOT NULL CHECK (exam_type IN ('TYT','AYT')),
    subject varchar(100) NOT NULL,
    booklet_position integer NOT NULL,
    UNIQUE (exam_year,exam_type,booklet_position)
);
INSERT INTO exam_archive_positions(question_id,exam_year,exam_type,subject,booklet_position)
SELECT q.id,v.exam_year,v.exam_type,v.subject,v.booklet_position
FROM (VALUES
{','.join(chr(10) + p for p in positions).lstrip()}
) AS v(code,exam_year,exam_type,subject,booklet_position)
JOIN questions q ON q.code=v.code AND q.bank='CIKMIS';
"""
    if OUTPUT.exists() and OUTPUT.read_text(encoding='utf-8') != sql:
        raise ValueError('Existing migration differs; create a new migration instead of rewriting published history')
    OUTPUT.write_text(sql, encoding='utf-8', newline='\n')
    registry = f"""-- Preserved identities survive question import/removal and an initially empty database.
-- Generated from the same source as V57; source SHA256 {hashlib.sha256(raw).hexdigest()}.
ALTER TABLE exam_archive_positions ADD COLUMN question_code varchar(200);
UPDATE exam_archive_positions a SET question_code=q.code FROM questions q WHERE q.id=a.question_id;
ALTER TABLE exam_archive_positions DROP CONSTRAINT exam_archive_positions_question_id_fkey;
ALTER TABLE exam_archive_positions DROP CONSTRAINT exam_archive_positions_pkey;
ALTER TABLE exam_archive_positions DROP COLUMN question_id;
ALTER TABLE exam_archive_positions ALTER COLUMN question_code SET NOT NULL;
ALTER TABLE exam_archive_positions ADD PRIMARY KEY(question_code);
INSERT INTO exam_archive_positions(question_code,exam_year,exam_type,subject,booklet_position)
SELECT v.code,v.exam_year,v.exam_type,CASE WHEN v.subject='Geometri' THEN 'Matematik' ELSE v.subject END,v.booklet_position
FROM (VALUES
{','.join(chr(10) + p for p in positions).lstrip()}
) AS v(code,exam_year,exam_type,subject,booklet_position)
ON CONFLICT(question_code) DO UPDATE SET subject=excluded.subject;
"""
    if REGISTRY_OUTPUT.exists() and REGISTRY_OUTPUT.read_text(encoding='utf-8') != registry:
        raise ValueError('Published registry migration differs')
    REGISTRY_OUTPUT.write_text(registry, encoding='utf-8', newline='\n')
    print(json.dumps({'output': str(REGISTRY_OUTPUT), 'individualPositions': len(positions)}))


if __name__ == '__main__':
    generate()
